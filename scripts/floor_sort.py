#!/usr/bin/env python3
"""floor_sort: the one-sitting sort of the rejection floor, as a proposal for Krish (W2.10). Never a floor change.

Krish, 2026-10-29: "I would much rather the engine know what kind of thing doesn't fly with me, rather than implement
incredibly specific rules everywhere which came from feedback on one piece of content for one specific reason." The
Wave 2 plan (W2.10) sorts the rejection floor's draft standards and its patterns into three places: the floor (his
eight nevers, which alone may block), aims (what great looks like, never blocking) and dated examples of the kind of
thing that does not fly. Only the patterns go to him, in one sitting of about fifteen minutes; the one-off drafts
become dated examples without asking him, because none of them blocks anything.

    python3 scripts/floor_sort.py                 # print the proposal (Markdown)
    python3 scripts/floor_sort.py --out FILE      # write it
    python3 scripts/floor_sort.py --self-test

The sort is the engine's reading: a pattern whose words name what one of the eight nevers already holds is proposed as
"held by never N"; any other pattern is proposed as an aim. He decides each one. Nothing here writes the floor file,
which only the Rejections engine renders and only his merge changes.
"""
import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FLOOR = ROOT / 'config' / 'rejection-floor.json'
BAR = ROOT / 'config' / 'reference-cuts.json'
# The words in a standard that point at what a never already holds (the engine's reading, for his sitting).
NEVER_WORDS = {
    'his_name': (r'\bkrish\b', r'\bauthor', r'\bbyline', r'\bhis name\b'),
    'nothing_made_up': (r'\bmade[- ]up\b', r'\bunsourced\b', r'\bcite', r'\bcredit(ed)? (the|its) (source|producer)', r'\bfabricat'),
    'every_word_in_sync': (r'\bchop', r'\bout of sync\b', r'\blip', r'\bmid-word\b', r'\bclipped word', r'\bcut (off|out) (a|his|my) word'),
    'empty_labels': (r'\beyebrow', r'\basterisk', r'generated by ai', r"\bkrish'?s take\b", r'\btake tag', r'\bread tag'),
    'nothing_goes_out_without_him': (r'\bpublish(ed)? without\b', r'\bwithout (his|my) yes\b', r'\bfull time\b', r'\bheartside\b'),
    'real_marks_with_rights': (r'\blogo', r'\bredraw', r'\bofficial mark', r'\bflag'),
    'one_opening_one_close': (r'\bintro', r'\boutro', r'\btwo (separate )?openings?\b', r'\bend card', r'\bclosing screen'),
    'no_em_dash_no_preaching': (r'\bem dash', r'\bpreach', r'\bmissionary'),
}


def never_of(text):
    t = str(text or '').lower()
    hits = [k for k, pats in NEVER_WORDS.items() if any(re.search(p, t) for p in pats)]
    return hits[0] if len(hits) == 1 else None


def sort(doc, bar):
    """(patterns: [(ref, standard, proposal)], examples: Counter of theme, nevers: {id: number})."""
    numbers = {n['id']: i for i, n in enumerate((bar.get('floor') or {}).get('nevers') or [], 1)}
    patterns, examples = [], Counter()
    for ref, s in sorted(doc['standards'].items(), key=lambda kv: (-(kv[1].get('productions') or 0), kv[0])):
        if s.get('weight') == 'pattern':
            text = ' '.join(str(s.get(k) or '') for k in ('never_beneath', 'in_his_words'))
            never = never_of(text)
            proposal = (f'held by never {numbers[never]} ({never})' if never in numbers else 'aim: guides the work, never blocks')
            patterns.append((ref, s, proposal))
        else:
            examples[s.get('theme') or 'other'] += 1
    return patterns, examples, numbers


def proposal(doc, bar):
    patterns, examples, numbers = sort(doc, bar)
    nevers = (bar.get('floor') or {}).get('nevers') or []
    lines = ['# The one-sitting floor sort: a proposal for Krish', '',
             f'Made by `scripts/floor_sort.py` from the rejection floor version {doc["version"][:12]} (as of {doc["as_of"]}). '
             'A proposal, never a floor change: the floor file changes only by a pull request you merge.', '',
             'Your words, 29 October 2026: "I would much rather the engine know what kind of thing doesn\'t fly with me, rather '
             'than implement incredibly specific rules everywhere which came from feedback on one piece of content for one '
             'specific reason."', '',
             '## What blocks', '', 'Only your eight nevers, as you confirmed them ("Yes, that\'s the floor"):', '']
    lines += [f'{i}. {n.get("listed")}' for i, n in enumerate(nevers, 1)]
    one_offs = sum(examples.values())
    lines += ['', '## What is proposed', '',
              f'- **{len(patterns)} patterns** (each raised about two or more productions) come to you below, one line each. '
              'For each, say "never N", "aim" or "drop".',
              f'- **{one_offs} one-off drafts** become dated examples of the kind of thing that does not fly, without asking you: '
              'none of them blocks, and each keeps its date and your words. By theme: '
              + ', '.join(f'{t} {n}' for t, n in examples.most_common()) + '.', '',
              '## The patterns, for your sitting', '',
              '| # | Pattern (the engine\'s wording) | Productions | Proposed |', '|---|---|---|---|']
    for n, (ref, s, prop) in enumerate(patterns, 1):
        # No em dashes in what he reads (never 8): the engine's wording keeps its sense with a colon.
        text = ' '.join(str(s.get('never_beneath') or '').split()).replace('|', '/').replace(' \u2014 ', ': ').replace('\u2014', ', ')
        lines.append(f'| {n} | {text} `{ref}` | {s.get("productions") or "?"} | {prop} |')
    lines += ['', 'Nevers 1 (no name) and 7 (one opening, one close) are promoted through this route once you merge the floor '
              'pull request the Rejections engine opens from your answers.', '']
    return '\n'.join(lines)


def self_test():
    doc = {'version': 'v' * 32, 'as_of': '2026-10-29',
           'standards': {'a': {'weight': 'pattern', 'productions': 3, 'never_beneath': 'Never run two separate intro sequences.', 'theme': 'structure'},
                         'b': {'weight': 'pattern', 'productions': 2, 'never_beneath': 'Never leave dead space in a frame.', 'theme': 'layout'},
                         'c': {'weight': 'one_off', 'never_beneath': 'Never hold a still.', 'theme': 'decorative_motion'}}}
    bar = {'floor': {'nevers': [{'id': k, 'listed': k} for k in NEVER_WORDS]}}
    patterns, examples, _ = sort(doc, bar)
    text = proposal(doc, bar)
    bad = []
    if [p for _, _, p in patterns] != ['held by never 7 (one_opening_one_close)', 'aim: guides the work, never blocks']:
        bad.append(f'a pattern a never holds is proposed as that never, any other as an aim ({patterns})')
    if examples != Counter({'decorative_motion': 1}):
        bad.append('a one-off draft becomes a dated example, counted by theme')
    if '2 patterns' not in text or '1 one-off drafts' not in text or 'never a floor change' not in text:
        bad.append('the proposal says what comes to him and what does not, and that it changes nothing')
    if never_of('Never use a logo or an intro') is not None:
        bad.append('a standard that names two nevers is not guessed')
    return bad


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out')
    ap.add_argument('--self-test', action='store_true')
    a = ap.parse_args(argv)
    if a.self_test:
        bad = self_test()
        print('floor_sort self-test ' + ('FAILED:\n  ' + '\n  '.join(bad) if bad else 'passed'))
        return 1 if bad else 0
    text = proposal(json.loads(FLOOR.read_text(encoding='utf-8')), json.loads(BAR.read_text(encoding='utf-8')))
    if a.out:
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(text, encoding='utf-8')
        print(f'wrote {a.out}')
    else:
        print(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
