import { readdirSync } from 'node:fs'
import { readFile } from 'node:fs/promises'
import { copyFields, copyLint, copyLintReason, COPY_LINT_VERSION } from '../apps/control-plane/api/_copyLint.js'

const config = JSON.parse(await readFile(new URL('../config/studio.json', import.meta.url), 'utf8')) as { series: Record<string, { public_name: string }> }
const names = Object.values(config.series).map((series) => series.public_name).sort()
// The retired pair stays for jobs made under it; the live subchannels are
// written lower case with dots, as the brand writes them.
const expected = ['Built With AI', 'The Money of AI', 'follow.the.money', 'mind.the.gap', 'under.the.hood'].sort()
if (JSON.stringify(names) !== JSON.stringify(expected)) throw new Error(`public series names drifted: ${names.join(', ')}`)
if (Object.values(config.series).some((series) => /^paid$|^built$/i.test(series.public_name))) throw new Error('legacy public series name found')

// The copy lint (Krish, 2026-10-28: "don't add stupid eyebrow text and asterisks
// and "generated by AI" and "Krish's take" verbal diahorrea"), on every public
// word the plans hold in the engine's own shapes: board materials (channel copy
// and titles), carousel cards, cover facts, creative directions and publish
// managers. The article bodies (draft-body and publish-body markdown) are read
// as article_body, where only the name rule runs (Krish, 2026-10-28: "Remember,
// no content refers to Krish, ever.").
const plans = new URL('../docs/plans/', import.meta.url)
const all = readdirSync(plans, { recursive: true, encoding: 'utf8' }).map((f) => f.replaceAll('\\', '/')).sort()
const files = all.filter((f) => f.endsWith('.json'))
const bodies = all.filter((f) => /(?:^|\/)[^/]*draft-body[^/]*\.md$|(?:^|\/)publish-body[^/]*\.md$/.test(f))
// Records filed before the 28 Oct ruling, named one by one: their name hits are
// shown as notices, never fixed in place, because they record what was filed.
// Any other hit in them still fails, and no new file joins this list.
const FILED_BEFORE_THE_NAME_RULING: Record<string, string> = {
  '2026-10-09-draft-body-v2.md': 'a superseded draft holding the old "[Krish to set]" placeholder',
  '2026-10-09-draft-body-v3.md': 'a superseded draft holding the old "[Krish to set]" placeholder',
  '2026-10-12-monday/manager.json': 'the 12 Oct publish manager as filed; its cover alt text names him; live post not checked, so Krish checks it and fixes it by hand',
  '2026-10-14-wednesday/manager.json': 'the 14 Oct publish manager as filed; its cover alt text names him; live post not checked, so Krish checks it and fixes it by hand',
  '2026-10-19-monday/publish-manager.json': 'the 19 Oct publish manager as filed; the live post does not carry its alt text',
}
const hits: string[] = []
const notices: string[] = []
const unreadable: string[] = []
let scanned = 0
const report = (rel: string, where: string, id: string, match: string) => {
  const line = `docs/plans/${rel} ${where}: ${id} ${JSON.stringify(match)}`
  if (id === 'no_name' && rel in FILED_BEFORE_THE_NAME_RULING) notices.push(`${line} (${FILED_BEFORE_THE_NAME_RULING[rel]})`)
  else hits.push(`${line}. ${copyLintReason(id)}`)
}
for (const rel of bodies) {
  scanned += 1
  const body = (await readFile(new URL(rel, plans), 'utf8')).replace(/^\uFEFF/, '')
  for (const hit of copyLint(body, 'article_body')) report(rel, `line ${body.slice(0, hit.index).split('\n').length}`, hit.id, hit.match)
}
for (const rel of files) {
  let data: unknown
  try {
    // A file saved on a Windows computer can start with a byte-order mark, which
    // JSON.parse refuses and copy_lint.py reads past; read past it here too.
    data = JSON.parse((await readFile(new URL(rel, plans), 'utf8')).replace(/^\uFEFF/, ''))
  } catch (error) {
    unreadable.push(`docs/plans/${rel}: ${(error as Error).message}`)
    continue
  }
  for (const field of copyFields(data)) {
    scanned += 1
    for (const hit of copyLint(field.text, field.appliesTo)) report(rel, field.where, hit.id, hit.match)
  }
}
const stale = Object.keys(FILED_BEFORE_THE_NAME_RULING).filter((rel) => !all.includes(rel))
if (stale.length) throw new Error(`copy lint: the filed-record list names files that are gone: ${stale.join(', ')}`)
// The check is never clean on a file it could not read.
if (unreadable.length) throw new Error(`copy lint ${COPY_LINT_VERSION}: ${unreadable.length} plan file(s) are not JSON, so their public words were not read\n${unreadable.join('\n')}`)
if (hits.length) throw new Error(`copy lint ${COPY_LINT_VERSION}: ${hits.length} hit(s) in public copy\n${hits.join('\n')}`)
if (notices.length) process.stdout.write(`notice: ${notices.length} name hit(s) in records filed before the 28 Oct ruling, left as filed\n${notices.join('\n')}\n`)
process.stdout.write(`public copy invariants passed (copy lint ${COPY_LINT_VERSION}: ${scanned} public fields and article bodies clean)\n`)
