import { readdirSync } from 'node:fs'
import { readFile } from 'node:fs/promises'
import { copyFields, copyLint, copyLintReason, COPY_LINT_VERSION } from '../apps/control-plane/api/_copyLint.js'

const config = JSON.parse(await readFile(new URL('../config/studio.json', import.meta.url), 'utf8')) as { series: Record<string, { public_name: string }> }
const names = Object.values(config.series).map((series) => series.public_name).sort()
// The retired pair stays for jobs made under it; the live subchannels are
// written lower case with dots, as the brand writes them.
const expected = ['Built With AI', 'The Money of AI', 'follow.the.money', 'mind.the.gap', 'under.the.hood'].sort()
if (JSON.stringify(names) !== JSON.stringify(expected)) throw new Error(`public series names drifted: ${names.join(', ')}`)
if (Object.values(config.series).some((series) => /^paid$|^built$/i.test(series.public_name))) throw new Error('legacy public series name found')

// The copy lint (Krish, 2026-10-28: "don't add stupid eyebrow text and asterisks
// and "generated by AI" and "Krish's take" verbal diahorrea"), on every public
// word the plans hold in the engine's own shapes: board materials (channel copy
// and titles), carousel cards, cover facts and creative directions. The article
// body's markdown is never read here.
const plans = new URL('../docs/plans/', import.meta.url)
const files = readdirSync(plans, { recursive: true, encoding: 'utf8' }).filter((f) => f.endsWith('.json')).sort()
const hits: string[] = []
const unreadable: string[] = []
let scanned = 0
for (const rel of files) {
  let data: unknown
  try {
    // A file saved on a Windows computer can start with a byte-order mark, which
    // JSON.parse refuses and copy_lint.py reads past; read past it here too.
    data = JSON.parse((await readFile(new URL(rel.replaceAll('\\', '/'), plans), 'utf8')).replace(/^\uFEFF/, ''))
  } catch (error) {
    unreadable.push(`docs/plans/${rel.replaceAll('\\', '/')}: ${(error as Error).message}`)
    continue
  }
  for (const field of copyFields(data)) {
    scanned += 1
    for (const hit of copyLint(field.text, field.appliesTo)) {
      hits.push(`docs/plans/${rel.replaceAll('\\', '/')} ${field.where}: ${hit.id} ${JSON.stringify(hit.match)}. ${copyLintReason(hit.id)}`)
    }
  }
}
// The check is never clean on a file it could not read.
if (unreadable.length) throw new Error(`copy lint ${COPY_LINT_VERSION}: ${unreadable.length} plan file(s) are not JSON, so their public words were not read\n${unreadable.join('\n')}`)
if (hits.length) throw new Error(`copy lint ${COPY_LINT_VERSION}: ${hits.length} hit(s) in public copy\n${hits.join('\n')}`)
process.stdout.write(`public copy invariants passed (copy lint ${COPY_LINT_VERSION}: ${scanned} public fields clean)\n`)
